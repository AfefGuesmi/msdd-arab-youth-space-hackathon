import 'package:flutter/material.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:latlong2/latlong.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:pdf/pdf.dart';
import 'package:printing/printing.dart';

import './danger_style.dart';

class PopupWidget extends StatelessWidget {
  final String debrisType;
  final String dangerLevel;
  final String solution;
  final LatLng coords;
  final VoidCallback onClose;

  // Asset path of the zone's qualitative-result image. Only used inside
  // the downloaded PDF report; the popup's own look is unchanged.
  final String? imagePath;

  const PopupWidget({
    super.key,
    required this.debrisType,
    required this.dangerLevel,
    required this.solution,
    required this.coords,
    required this.onClose,
    this.imagePath,
  });

  // Same navy palette as the sidebars and the sign-in/sign-up pages, so
  // the popup reads as part of the same design system instead of its
  // own separate colour.
  static const Color navyBlue = Color(0xFF1A1F33);
  static const Color darkNavy = Color(0xFF0A0E1A);
  static const String _fontFamily = 'Times New Roman';

  Future<pw.MemoryImage?> _loadPdfImage() async {
    final path = imagePath;
    if (path == null) return null;
    try {
      final data = await rootBundle.load(path);
      return pw.MemoryImage(data.buffer.asUint8List());
    } catch (_) {
      return null;
    }
  }

  Future<void> _generatePdf(BuildContext context) async {
    final pdf = pw.Document();
    final now = DateTime.now();

    // Embed the zone's image if it can be loaded; otherwise the report
    // is generated without it instead of failing.
    final pw.MemoryImage? image = await _loadPdfImage();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.Text("Debris Report",
                style: pw.TextStyle(
                    fontSize: 20, fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 5),
            pw.Divider(thickness: 2),
          ],
        ),
        footer: (context) => pw.Column(
          children: [
            pw.Divider(thickness: 2),
            pw.SizedBox(height: 5),
            pw.Text("Generated by Ocean Debris Detection App",
                style: const pw.TextStyle(fontSize: 10)),
          ],
        ),
        build: (pw.Context context) => [
          pw.SizedBox(height: 30),
          pw.Center(
            child: pw.Table.fromTextArray(
              border: pw.TableBorder.all(width: 1),
              headerStyle: pw.TextStyle(
                  fontWeight: pw.FontWeight.bold, fontSize: 14),
              cellStyle: const pw.TextStyle(fontSize: 12),
              headers: ["Field", "Details"],
              data: [
                ["Debris Type", debrisType],
                ["Danger Level", dangerLevel],
                ["Geolocation", "${coords.latitude}, ${coords.longitude}"],
                ["Recommended Action", solution],
                [
                  "Report Date",
                  "${now.day}/${now.month}/${now.year} ${now.hour}:${now.minute}"
                ],
              ],
            ),
          ),
          // The image sits under the table, in the middle of the page.
          // A full-width Row with centred content is what really centres
          // it — a lone Column only shrinks to the picture and sits left.
          if (image != null) ...[
            pw.SizedBox(height: 24),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.center,
              children: [
                pw.Column(
                  mainAxisSize: pw.MainAxisSize.min,
                  crossAxisAlignment: pw.CrossAxisAlignment.center,
                  children: [
                    pw.Text("Qualitative result",
                        style: const pw.TextStyle(
                            fontSize: 10, color: PdfColors.grey700)),
                    pw.SizedBox(height: 6),
                    pw.Image(image, height: 220, fit: pw.BoxFit.contain),
                  ],
                ),
              ],
            ),
          ],
        ],
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
    );
  }

  // Small "label above value" row — a cleaner, more editorial way to
  // present each field than an icon-and-sentence line.
  Widget _infoRow(String label, String value, {Color? valueColor}) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            label.toUpperCase(),
            style: const TextStyle(
              color: Colors.white38,
              fontSize: 9.5,
              letterSpacing: 1.1,
              fontFamily: _fontFamily,
              fontWeight: FontWeight.w600,
            ),
          ),
          const SizedBox(height: 3),
          Text(
            value,
            style: TextStyle(
              color: valueColor ?? Colors.white,
              fontSize: 13,
              fontFamily: _fontFamily,
              fontWeight: FontWeight.w500,
            ),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final dangerColor = DangerStyle.color(dangerLevel);

    return Center(
      child: Material(
        color: Colors.transparent,
        child: Container(
          margin: const EdgeInsets.only(top: 50),
          width: MediaQuery.of(context).size.width * 0.85,
          padding: const EdgeInsets.fromLTRB(20, 14, 20, 20),
          decoration: BoxDecoration(
            // Same gradient as the sidebars, instead of its own
            // separate colour scheme.
            gradient: const LinearGradient(
              colors: [darkNavy, navyBlue],
              begin: Alignment.topCenter,
              end: Alignment.bottomCenter,
            ),
            borderRadius: BorderRadius.circular(16),
            border: Border.all(color: Colors.white.withOpacity(0.08)),
            boxShadow: [
              BoxShadow(
                color: Colors.black.withOpacity(0.55),
                blurRadius: 20,
                offset: const Offset(0, 8),
              ),
            ],
          ),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              // Header: a small danger-coloured badge, the debris type as
              // the title, and a subtle circular close button — reads
              // more like a card header than a loose icon + text row.
              Row(
                crossAxisAlignment: CrossAxisAlignment.center,
                children: [
                  Container(
                    width: 34,
                    height: 34,
                    decoration: BoxDecoration(
                      shape: BoxShape.circle,
                      color: dangerColor.withOpacity(0.16),
                      border: Border.all(color: dangerColor.withOpacity(0.6)),
                    ),
                    child: Icon(Icons.warning_rounded,
                        color: dangerColor, size: 17),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Text(
                      debrisType,
                      style: const TextStyle(
                        color: Colors.white,
                        fontSize: 15,
                        fontWeight: FontWeight.bold,
                        fontFamily: _fontFamily,
                      ),
                    ),
                  ),
                  InkWell(
                    onTap: onClose,
                    customBorder: const CircleBorder(),
                    child: Container(
                      width: 28,
                      height: 28,
                      alignment: Alignment.center,
                      decoration: BoxDecoration(
                        shape: BoxShape.circle,
                        color: Colors.white.withOpacity(0.06),
                      ),
                      child: const Icon(Icons.close,
                          color: Colors.white70, size: 16),
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 14),
              Divider(color: Colors.white.withOpacity(0.08), height: 1),
              const SizedBox(height: 16),
              _infoRow("Danger level", dangerLevel, valueColor: dangerColor),
              _infoRow(
                "Coordinates",
                "${coords.latitude.toStringAsFixed(4)}, ${coords.longitude.toStringAsFixed(4)}",
              ),
              _infoRow("Recommended action", solution),
              const SizedBox(height: 6),
              InkWell(
                borderRadius: BorderRadius.circular(10),
                onTap: () => _generatePdf(context),
                child: Container(
                  width: double.infinity,
                  padding:
                      const EdgeInsets.symmetric(vertical: 11, horizontal: 16),
                  decoration: BoxDecoration(
                    color: navyBlue,
                    borderRadius: BorderRadius.circular(10),
                    border: Border.all(color: Colors.white.withOpacity(0.12)),
                    boxShadow: [
                      BoxShadow(
                        color: Colors.black.withOpacity(0.35),
                        blurRadius: 10,
                        offset: const Offset(0, 3),
                      ),
                    ],
                  ),
                  child: Row(
                    mainAxisAlignment: MainAxisAlignment.center,
                    mainAxisSize: MainAxisSize.min,
                    children: const [
                      Icon(Icons.picture_as_pdf_outlined,
                          color: Colors.white, size: 17),
                      SizedBox(width: 8),
                      Text(
                        "Download report",
                        style: TextStyle(
                          color: Colors.white,
                          fontSize: 13,
                          fontFamily: _fontFamily,
                          fontWeight: FontWeight.w600,
                        ),
                      ),
                    ],
                  ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}