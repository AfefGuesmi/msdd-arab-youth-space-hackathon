import 'package:flutter/material.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:latlong2/latlong.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:pdf/pdf.dart';
import 'package:printing/printing.dart';


// Reports live in their own dedicated sidebar panel, separate from
// Notifications — each has its own button in the circular menu and its own
// sliding panel in map.dart. The PDFs carry the zone's image under the table.
class ReportsSidebar extends StatelessWidget {
  final List<Map<String, dynamic>> zones;

  const ReportsSidebar({
    Key? key,
    required this.zones,
  }) : super(key: key);

  static const String _fontFamily = 'Times New Roman';

  // Loads a zone's image from the app assets so it can be embedded in a
  // PDF. Returns null (and the PDF simply omits the image) if the asset is
  // missing, so a bad path never blocks the report from generating.
  Future<pw.MemoryImage?> _loadPdfImage(String? assetPath) async {
    if (assetPath == null) return null;
    try {
      final data = await rootBundle.load(assetPath);
      return pw.MemoryImage(data.buffer.asUint8List());
    } catch (_) {
      return null;
    }
  }

  // The image block shared by the single-zone and global PDFs. It goes
  // UNDER the table, in the middle of the page. A full-width Row with
  // centred content is what really centres it — a lone Column only shrinks
  // to the picture's width and sits on the left.
  pw.Widget _pdfImageBlock(pw.MemoryImage image) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.center,
      children: [
        pw.Column(
          mainAxisSize: pw.MainAxisSize.min,
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.Image(image, height: 220, fit: pw.BoxFit.contain),
          ],
        ),
      ],
    );
  }

  // --- Generate PDF for a single zone ---
  Future<void> _generateZonePdf(Map<String, dynamic> zone) async {
    final pdf = pw.Document();
    final now = DateTime.now();
    final coords = zone["center"] as LatLng;
    final image = await _loadPdfImage(zone["image"] as String?);

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.Text("Debris Report",
                style: pw.TextStyle(
                    fontSize: 20, fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 5),
            pw.Divider(thickness: 2),
          ],
        ),
        footer: (context) => pw.Column(
          children: [
            pw.Divider(thickness: 2),
            pw.SizedBox(height: 5),
            pw.Text("Generated by Ocean Debris Detection App",
                style: const pw.TextStyle(fontSize: 10)),
          ],
        ),
        build: (pw.Context context) => [
          pw.SizedBox(height: 30),
          pw.Table.fromTextArray(
            border: pw.TableBorder.all(width: 1),
            headerStyle: pw.TextStyle(
                fontWeight: pw.FontWeight.bold, fontSize: 14),
            cellStyle: const pw.TextStyle(fontSize: 12),
            headers: ["Field", "Details"],
            data: [
              ["Debris Type", zone["type"]],
              ["Danger Level", zone["danger"]],
              ["Geolocation", "${coords.latitude}, ${coords.longitude}"],
              ["Recommended Action", zone["solution"]],
              [
                "Report Date",
                "${now.day}/${now.month}/${now.year} ${now.hour}:${now.minute}"
              ],
            ],
          ),
          // Under the table, centred.
          if (image != null) ...[
            pw.SizedBox(height: 24),
            _pdfImageBlock(image),
          ],
        ],
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
    );
  }

  // --- Generate the global report ---
  Future<void> _generateGlobalPdf() async {
    final pdf = pw.Document();
    final now = DateTime.now();

    // Load every zone's image up front (the PDF build step is synchronous).
    // The zones share only three pictures, so each one is loaded once and
    // reused — this keeps the global report's file size and time down.
    final Map<String, pw.MemoryImage?> cache = {};
    for (final zone in zones) {
      final String? path = zone["image"] as String?;
      if (path != null && !cache.containsKey(path)) {
        cache[path] = await _loadPdfImage(path);
      }
    }
    final List<pw.MemoryImage?> images = [
      for (final zone in zones) cache[zone["image"] as String?],
    ];

    // One page per detected area.
    for (int i = 0; i < zones.length; i++) {
      final zone = zones[i];
      final image = images[i];
      final coords = zone["center"] as LatLng;

      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          margin: const pw.EdgeInsets.all(32),
          build: (pw.Context context) => pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Center(
                child: pw.Text("Global Debris Report",
                    style: pw.TextStyle(
                        fontSize: 20, fontWeight: pw.FontWeight.bold)),
              ),
              pw.SizedBox(height: 5),
              pw.Divider(thickness: 2),
              pw.SizedBox(height: 16),
              pw.Text("Report for ${zone["type"]}",
                  style: pw.TextStyle(
                      fontSize: 16, fontWeight: pw.FontWeight.bold)),
              pw.SizedBox(height: 4),
              pw.Text("Area ${i + 1} of ${zones.length}",
                  style: const pw.TextStyle(
                      fontSize: 10, color: PdfColors.grey700)),
              pw.SizedBox(height: 10),
              pw.Table.fromTextArray(
                border: pw.TableBorder.all(width: 1),
                headerStyle: pw.TextStyle(
                    fontWeight: pw.FontWeight.bold, fontSize: 14),
                cellStyle: const pw.TextStyle(fontSize: 12),
                headers: ["Field", "Details"],
                data: [
                  ["Debris Type", zone["type"]],
                  ["Danger Level", zone["danger"]],
                  ["Geolocation", "${coords.latitude}, ${coords.longitude}"],
                  ["Recommended Action", zone["solution"]],
                  [
                    "Report Date",
                    "${now.day}/${now.month}/${now.year} ${now.hour}:${now.minute}"
                  ],
                ],
              ),
              // Under the table, centred.
              if (image != null) ...[
                pw.SizedBox(height: 24),
                _pdfImageBlock(image),
              ],
              pw.Spacer(),
              pw.Divider(thickness: 2),
              pw.SizedBox(height: 5),
              pw.Center(
                child: pw.Text("Generated by Ocean Debris Detection App",
                    style: const pw.TextStyle(fontSize: 10)),
              ),
            ],
          ),
        ),
      );
    }

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
    );
  }

  @override
  Widget build(BuildContext context) {
    // No Drawer/tab wrapper here — this widget is embedded directly inside
    // the sliding right-side panel built in map.dart, which already
    // provides the background and title bar.
    return Column(
      children: [
        Expanded(
          child: ListView.builder(
            padding: const EdgeInsets.symmetric(vertical: 4),
            itemCount: zones.length,
            itemBuilder: (context, index) {
              final zone = zones[index];
              final coords = zone["center"] as LatLng;
              // Text only: the title, the debris type and the geolocation
              // of the area, plus the download button.
              return ListTile(
                contentPadding:
                    const EdgeInsets.symmetric(horizontal: 16, vertical: 4),
                title: Text(
                  zone["type"],
                  style: const TextStyle(
                    color: Colors.white,
                    fontFamily: _fontFamily,
                    fontSize: 13,
                    fontWeight: FontWeight.w600,
                  ),
                ),
                subtitle: Text(
                  "${zone["ocean"]}\n${coords.latitude.toStringAsFixed(4)}, ${coords.longitude.toStringAsFixed(4)}",
                  style: const TextStyle(
                    color: Colors.white70,
                    fontFamily: _fontFamily,
                    fontSize: 11,
                    height: 1.35,
                  ),
                ),
                isThreeLine: true,
                trailing: IconButton(
                  tooltip: "Download report",
                  icon: const Icon(Icons.download,
                      color: Colors.white, size: 20),
                  onPressed: () => _generateZonePdf(zone),
                ),
              );
            },
          ),
        ),
        const Divider(color: Colors.white54),
        ListTile(
          dense: true,
          title: const Text(
            "Download global report",
            style: TextStyle(
              color: Colors.white,
              fontFamily: _fontFamily,
              fontSize: 13,
            ),
          ),
          trailing: const Icon(Icons.download_for_offline,
              color: Colors.white, size: 20),
          onTap: _generateGlobalPdf,
        ),
      ],
    );
  }
}
